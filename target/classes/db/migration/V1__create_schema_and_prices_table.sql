CREATE SCHEMA IF NOT EXISTS ZARA;
SET SCHEMA ZARA;

CREATE TABLE IF NOT EXISTS PRICES (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  BRAND_ID INT NOT NULL,
  PRODUCT_ID INT NOT NULL,
  PRICE_LIST INT NOT NULL,
  START_DATE TIMESTAMP NOT NULL,
  END_DATE TIMESTAMP NOT NULL,
  PRIORITY INT NOT NULL,
  PRICE DECIMAL(10,2) NOT NULL,
  CURR VARCHAR(3) NOT NULL
);

ALTER TABLE PRICES
  ADD CONSTRAINT UK_PRICES_BRAND_PRODUCT_START_END
  UNIQUE (BRAND_ID, PRODUCT_ID, START_DATE, END_DATE);

CREATE INDEX IDX_PRICES_PRODUCT_BRAND_DATE
  ON PRICES (PRODUCT_ID, BRAND_ID, START_DATE, END_DATE);

CREATE INDEX IDX_PRICES_PRODUCT_BRAND
  ON PRICES (PRODUCT_ID, BRAND_ID);
